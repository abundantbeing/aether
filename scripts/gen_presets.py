"""Write the normalized presets, and the finishes the editor offers, into desktop-src/presets.generated.js.

The Python half is the one source of truth for theme maths (palette derivation, the readability
floor, scene clamping). The Desktop half ships the presets already normalized, so the gallery works
before the agent half answers, and a preset can never drift from what the agent would produce.

    python scripts/gen_presets.py           # write
    python scripts/gen_presets.py --check   # exit 1 when the committed file is stale
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "desktop-src" / "presets.generated.js"


def load_package():
    spec = importlib.util.spec_from_file_location("aether_plugin", ROOT / "__init__.py",
                                                  submodule_search_locations=[str(ROOT)])
    module = importlib.util.module_from_spec(spec)
    sys.modules["aether_plugin"] = module
    # Only the pure modules are needed; importing the package entry is not.
    for name in ("_svg", "_color", "_palette", "_spec", "_presets"):
        sub = importlib.util.spec_from_file_location(f"aether_plugin.{name}", ROOT / f"{name}.py")
        mod = importlib.util.module_from_spec(sub)
        sys.modules[f"aether_plugin.{name}"] = mod
        sub.loader.exec_module(mod)
    return sys.modules["aether_plugin._presets"]


def render() -> str:
    presets = load_package().preset_records()
    spec = sys.modules["aether_plugin._spec"]
    for record in presets:
        record.pop("adjustments", None)
        record.pop("spec", None)
    finishes = [{"style": style, "description": text, "pixel": spec.FINISH_PIXEL.get(style, 2)}
                for style, text in spec.FINISHES.items()]
    body = json.dumps(presets, indent=2, ensure_ascii=False)
    return ("// Generated by scripts/gen_presets.py from _presets.py and _spec.py. Do not edit by hand.\n"
            f"export const PRESETS = {body}\n"
            f"export const FINISHES = {json.dumps(finishes, indent=2, ensure_ascii=False)}\n"
            f"export const PATTERNS = {json.dumps(list(spec.PATTERNS))}\n")


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("desktop-src/presets.generated.js is stale: run python scripts/gen_presets.py", file=sys.stderr)
            return 1
        print("presets.generated.js is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
